'use client';

import { useRef, useState } from 'react';
import { ScientificPlot } from './cove-science';

type Comparison = {
  subject:string; condition:number; seed:number; channels:string[];
  measured:number[][]; cortical_readout:number[][];
};

function parse(text:string):Comparison {
  const value=JSON.parse(text);
  const channelCount=value?.channels?.length;
  const finiteRow=(row:unknown)=>Array.isArray(row)&&row.length===30&&row.every(Number.isFinite);
  const matrix=(data:unknown)=>Array.isArray(data)&&data.length===channelCount&&data.every(finiteRow);
  if(value?.schema!=='cove-measured-erp-v1'||typeof value.subject!=='string'||!/^\d{2}$/.test(value.subject)||
    !Number.isInteger(value.condition)||value.condition<1||value.condition>200||!Number.isInteger(value.seed)||
    !Array.isArray(value.channels)||channelCount<1||channelCount>63||
    !value.channels.every((name:unknown)=>typeof name==='string'&&name.length>0&&name.length<=12)||
    !Array.isArray(value.times_ms)||value.times_ms.length!==30||!value.times_ms.every((t:unknown,i:number)=>t===10+20*i)||
    !matrix(value.measured)||!matrix(value.cortical_readout)) {
    throw new Error('Choose an onset-aligned ERP comparison JSON generated by the pilot script.');
  }
  return value;
}

export default function MeasuredErp() {
  const [comparison,setComparison]=useState<Comparison>();
  const [channel,setChannel]=useState(0);
  const [error,setError]=useState('');
  const version=useRef(0);
  return <section className="science-stack measured-erp" aria-labelledby="measured-erp-title">
    <h2 id="measured-erp-title">Measured EEG comparison</h2>
    <p>Load a local THINGS-EEG2 pilot comparison to inspect its held-out, onset-aligned trial average and calibrated prediction on the same scale. The comparison has its own stimulus and clock.</p>
    <label>ERP comparison JSON <input type="file" accept=".json,application/json" onChange={async event=>{
      const file=event.target.files?.[0];
      const request=++version.current;
      setComparison(undefined);setError('');
      if(!file)return;
      try {
        if(file.size>1024*1024)throw new Error('The comparison exceeds the 1 MiB limit.');
        const next=parse(await file.text());
        if(request===version.current){setComparison(next);setChannel(0);}
      }catch(problem){
        if(request===version.current)setError(problem instanceof Error?problem.message:'The comparison could not be read.');
      }
    }}/></label>
    {error&&<p role="alert">{error}</p>}
    {comparison&&<>
      <p>Participant {comparison.subject} · condition {comparison.condition} · held-out split {comparison.seed}</p>
      <label>EEG channel <select value={channel} onChange={event=>setChannel(Number(event.target.value))}>
        {comparison.channels.map((name,i)=><option key={i} value={i}>{name}</option>)}
      </select></label>
      <ScientificPlot title="Held-out stimulus ERP" unit="Pilot scaled CSD units" series={[
        {name:'Measured EEG trial average',color:'#176890',data:comparison.measured[channel]},
        {name:'Calibrated hybrid + cortical prediction',color:'#9a4d1f',data:comparison.cortical_readout[channel],dashed:true},
      ]} rate={.05} domain={[0,29]} offset={.5} xUnit="ms"/>
    </>}
  </section>;
}
